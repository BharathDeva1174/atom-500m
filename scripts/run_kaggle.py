"""Generate the ready-to-paste Kaggle notebook cell that trains Atom-500M.

Run locally to print the cell:
    python scripts/run_kaggle.py

Then paste the output into a Kaggle notebook with the **GPU T4 x2** accelerator.
Prerequisites in the Kaggle UI (not in the cell, since they're UI actions):
  1. Add the `HF_TOKEN` secret (Settings -> Secrets -> Add New Secret).
  2. Enable the T4 x2 accelerator.
  3. Attach the GPU and Internet toggles.

Why the cell is printed rather than run: this script generates a build artifact.
The notebook is the execution environment, so `run_kaggle.py` has no reason to
import torch, allocate a GPU, or know anything about Kaggle's runtime.
"""

import argparse
import sys

REPO_URL = "https://github.com/BharathDeva1174/atom-500m.git"
REPO_DIR = "atom-500m"
NPROC = 2  # Kaggle T4 x2

# Hugging Face upload target. The GitHub clone above is the *source* repo; this
# is where trained checkpoints land. Override with HF_REPO_ID to push elsewhere.
HF_REPO_ID_DEFAULT = "siddhu1174/atom-500m"


def build_cell(
    repo_url: str = REPO_URL,
    repo_dir: str = REPO_DIR,
    nproc: int = NPROC,
    with_dataset: bool = True,
) -> str:
    """Return the notebook cell source as a string.

    Deliberately verbose: this is pasted into a web UI with no editor
    autocomplete and no way to see the repo's own docs, so every step explains
    what it does and why.
    """
    parts = []
    parts.append(
        f'''\
# =============================================================================
# Atom-500M — Kaggle training cell
# Generated by scripts/run_kaggle.py. Paste into a notebook with GPU T4 x2.
#
# What this cell does, in order:
#   1. Reads HF_TOKEN from Kaggle's secret store (never hardcoded).
#   2. Verifies both T4 GPUs are actually visible — torchrun on a 1-GPU session
#      would hang instead of failing, so this check comes first.
#   3. Clones the repo.
#   4. Installs dependencies.
#   5. Mounts/checks the training corpus.
#   6. Launches torchrun across both GPUs.
# =============================================================================

import os
import subprocess
import sys

# --- 1. secrets ------------------------------------------------------------
from kaggle_secrets import UserSecretsClient

secrets = UserSecretsClient()
HF_TOKEN = secrets.get_secret("HF_TOKEN")
HF_REPO_ID = os.environ.get("HF_REPO_ID", "{HF_REPO_ID_DEFAULT}")

# Keep the token out of the printed environment and out of `ps` output.
os.environ["HF_TOKEN"] = HF_TOKEN
os.environ["HF_REPO_ID"] = HF_REPO_ID
assert HF_TOKEN, "HF_TOKEN secret not found — add it in Settings -> Secrets"

# --- 2. sanity-check the accelerator --------------------------------------
import torch

n_gpu = torch.cuda.device_count()
print(f"torch {{torch.__version__}} | GPUs visible: {{n_gpu}}")
for i in range(n_gpu):
    print(f"  cuda:{{i}} -> {{torch.cuda.get_device_name(i)}}")

if n_gpu < {nproc}:
    raise RuntimeError(
        f"Expected {nproc} GPUs (T4 x2), found {{n_gpu}}. "
        "Turn on the T4 x2 accelerator and re-run this cell — torchrun with "
        "--nproc_per_node={nproc} on a single GPU will hang, not fail."
    )

# fp16 Tensor Core check — the training loop depends on this for speed.
assert torch.cuda.is_available(), "CUDA unavailable; the accelerator is off."
'''
    )

    parts.append(
        f'''\
# --- 3. clone the repository ----------------------------------------------
REPO_URL = "{repo_url}"
REPO_DIR = "{repo_dir}"
# Anchor absolutely: os.chdir persists in the kernel, so a relative REPO_DIR
# nests one level deeper on every cell re-run (atom-500m/atom-500m/...).
REPO_ROOT = os.path.join("/kaggle/working", REPO_DIR)

if os.path.isdir(os.path.join(REPO_ROOT, ".git")):
    # Already cloned in an earlier cell of this notebook session.
    print(f"{{REPO_ROOT}} already exists — pulling latest instead of cloning")
    subprocess.run(["git", "-C", REPO_ROOT, "pull", "--ff-only"], check=False)
else:
    subprocess.run(["git", "clone", "{repo_url}", REPO_ROOT], check=True)

os.chdir(REPO_ROOT)
print("cwd:", os.getcwd())
'''
    )

    parts.append(
        f'''\
# --- 4. dependencies -------------------------------------------------------
subprocess.run(
    [sys.executable, "-m", "pip", "install", "-q", "-r", "requirements.txt"],
    check=True,
)
print("dependencies installed from requirements.txt")
'''
    )

    if with_dataset:
        parts.append(
            f'''\
# --- 5. training corpus ----------------------------------------------------
# Preferred: uint16 .bin shards built by scripts/prepare_dataset.py.
# Sources, in order: (1) shards copied from an attached Kaggle dataset,
# (2) built here from RAW_JSONL / HF_DATASET, (3) downloaded from the
# Hugging Face Hub by train_kaggle.py (ensure_shards) after launch.
SHARD_DIR = "data/shards"
os.makedirs(SHARD_DIR, exist_ok=True)

def _attached_shards():
    import glob
    return [p for p in glob.glob("/kaggle/input/**/*.bin", recursive=True)
            if os.path.getsize(p) > 1_000_000]

if not any(f.endswith(".bin") for f in os.listdir(SHARD_DIR)):
    print("No shards in", SHARD_DIR, "- looking for a source ...")
    print("/kaggle/input:",
          os.listdir("/kaggle/input") if os.path.isdir("/kaggle/input") else "(nothing attached)")
    attached = _attached_shards()
    if attached:
        import shutil
        print(f"copying {{len(attached)}} shard(s) from /kaggle/input ...")
        for p in attached:
            shutil.copy2(p, SHARD_DIR)
    else:
        RAW_JSONL = os.environ.get("RAW_JSONL", "")
        HF_DATASET = os.environ.get("HF_DATASET", "")

        cmd = [sys.executable, "scripts/prepare_dataset.py",
               "--out_dir", SHARD_DIR, "--block_size", "2048"]
        if RAW_JSONL:
            cmd += ["--input", RAW_JSONL]
        if HF_DATASET:
            cmd += ["--hf_dataset", HF_DATASET]

        if RAW_JSONL or HF_DATASET:
            subprocess.run(cmd, check=True)
        else:
            # Not an error: train_kaggle.py downloads data/*.bin from the Hub
            # on first run. Raising here would block that path entirely.
            print("No local shards or build inputs - deferring to the Hub "
                  "download inside train_kaggle.py (ensure_shards).")

shards = sorted(f for f in os.listdir(SHARD_DIR) if f.endswith(".bin"))
n_bytes = sum(os.path.getsize(os.path.join(SHARD_DIR, s)) for s in shards)
print(f"corpus: {{len(shards)}} shard(s), {{n_bytes / 1e9:.2f}} GB, "
      f"~{{n_bytes // 2 // 2049:,}} chunks")

if n_bytes < 200 * 1024**2:
    print(
        "NOTE: under 200 MB is roughly under 50M tokens — enough for a smoke "
        "test, thin for empathetic SFT. Expect the model to underfit."
    )
'''
        )

    parts.append(
        f'''\
# --- 6. launch distributed training ----------------------------------------
# scripts/train_kaggle.py bootstraps its own process group, so no torchrun
# here: run it as a plain script and it will launch 2 workers itself.
#
# It also downloads data/*.bin from the Hub on first run (444 MB), memory-maps
# them, and pushes checkpoints back as it goes.
env = os.environ.copy()
env.update({{
    "HF_TOKEN": HF_TOKEN,
    "HF_REPO_ID": HF_REPO_ID,
    "ATOM_SHARD_DIR": SHARD_DIR,   # uint16 .bin shards from prepare_dataset.py
    "ATOM_BATCH_SIZE": "4",        # per GPU
    "ATOM_GRAD_ACCUM": "4",        # 4 x 4 x 2 GPUs x 2048 = 65,536 tok/step
    "ATOM_LR": "3e-4",
    "ATOM_SAVE_EVERY": "500",
    "ATOM_EVAL_EVERY": "100",    # decoupled: eval is free, checkpointing is not
    "TOKENIZERS_PARALLELISM": "false",
    "PYTHONUNBUFFERED": "1",       # stream logs to the notebook as they happen
}})

subprocess.run([sys.executable, "scripts/train_kaggle.py"], env=env, check=True)

print("Training finished. Checkpoints were pushed to:", HF_REPO_ID)
'''
    )

    return "\n".join(parts)


def main():
    parser = argparse.ArgumentParser(
        description="Print the Atom-500M Kaggle notebook cell.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--repo-url", default=REPO_URL)
    parser.add_argument("--repo-dir", default=REPO_DIR)
    parser.add_argument("--nproc", type=int, default=NPROC,
                        help="GPU count (2 for Kaggle T4 x2)")
    parser.add_argument("--no-dataset", action="store_true",
                        help="omit the corpus check (e.g. if data arrives later)")
    parser.add_argument("--out", default=None,
                        help="also write the cell to this file (default: stdout only)")
    args = parser.parse_args()

    cell = build_cell(args.repo_url, args.repo_dir, args.nproc, not args.no_dataset)

    print(cell)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(cell)
        print(f"\n# written to {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
